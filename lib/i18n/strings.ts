const dictionaries: Record<Language, Dictionary> = { en: {}, hi, or };

/** Looks up a string; falls back to the English text and fills {placeholders}. */
export function translate(
  language: Language,
  text: string,
  vars?: Record<string, string | number>,
): string {
  const template = dictionaries[language][text] ?? text;
  return vars
    ? template.replace(/\{(\w+)\}/g, (match, key: string) =>
        key in vars ? String(vars[key]) : match,
      )
    : template;
}

export function isLanguage(value: unknown): value is Language {
  return value === "en" || value === "hi" || value === "or";
}
